    private static func soft(_ stem: String) -> Bool { "кгхжшщч".contains(stem.last!) }

    /// Словарь «слово с е» -> «слово с ё», в нижнем регистре.
    static let map: [String: String] = {
        var forms: [String] = words.split(whereSeparator: \.isWhitespace).map { $0.lowercased() }
        for s in nounsF.split(separator: " ").map(String.init) {
            forms += [soft(s) ? "и" : "ы", "а", "е", "у", "ой", "ам", "ами", "ах"].map { s + $0 }
        }
        for s in nounsM.split(separator: " ").map(String.init) {
            forms += ["", "а", "у", "е", "ом", "ы", "ов", "ам", "ами", "ах"].map { s + $0 }
        }
        for s in adjectives.split(whereSeparator: \.isWhitespace).map(String.init) {
            let i = soft(s) ? "и" : "ы"
            forms += ["\(i)й", "ая", "ое", "\(i)е", "ого", "ой", "ую", "ому", "\(i)м", "\(i)х", "\(i)ми"].map { s + $0 }
        }
        var m: [String: String] = [:]
        for f in forms { m[f.replacingOccurrences(of: "ё", with: "е")] = f }
        return m
    }()

    /// Возвращает слово с ё (с сохранением регистра) или nil.
    static func fix(_ word: String) -> String? {
        guard let y = map[word.lowercased()] else { return nil }
        let out = zip(word, y).map { orig, new in orig.isUppercase ? Character(String(new).uppercased()) : new }
        let s = String(out)
        return s == word ? nil : s
    }
